function polygonToPath(poly: Polygon, w: number, h: number): string {
  return (
    poly
      .map(([lng, lat], i) => {
        const x = ((lng + 180) / 360) * w;
        const y = ((90 - lat) / 180) * h;
        return `${i === 0 ? "M" : "L"} ${x.toFixed(1)} ${y.toFixed(1)}`;
      })
      .join(" ") + " Z"
  );
}

export function buildLandPaths(w: number, h: number): string[] {
  return ALL_POLYGONS.map((poly) => polygonToPath(poly, w, h));
}

/** Backwards compatibility — pre-projected for the default 960×480 viewBox. */
export const WORLD_LAND_PATHS: string[] = buildLandPaths(960, 480);
